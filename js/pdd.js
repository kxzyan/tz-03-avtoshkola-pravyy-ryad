// Тренажёр ПДД (pdd-test.html): 10 вопросов, 3 варианта, пояснение со ссылкой на пункт ПДД.
// Вопросы составлены по Правилам дорожного движения РФ (Постановление Правительства РФ от 23.10.1993 № 1090).
// Картинки из официальных экзаменационных билетов не используются.
(function () {
  var PDD = 'https://www.consultant.ru/document/cons_doc_LAW_2709/';
  var Q = [
    { q: 'Какая максимальная скорость разрешена легковому автомобилю в населённом пункте, если знаки не устанавливают другое ограничение?',
      a: ['50 км/ч', '60 км/ч', '70 км/ч'], r: 1, p: '10.2',
      e: 'В населённых пунктах разрешается движение транспортных средств со скоростью не более 60 км/ч.' },
    { q: 'С какой максимальной скоростью можно ехать на легковом автомобиле вне населённого пункта по обычной дороге (не автомагистрали)?',
      a: ['80 км/ч', '90 км/ч', '110 км/ч'], r: 1, p: '10.3',
      e: 'Вне населённых пунктов легковым автомобилям разрешено движение на автомагистралях до 110 км/ч, на остальных дорогах — до 90 км/ч.' },
    { q: 'Какая максимальная скорость разрешена легковому автомобилю на автомагистрали?',
      a: ['110 км/ч', '120 км/ч', '130 км/ч'], r: 0, p: '10.3',
      e: 'На автомагистралях легковым автомобилям разрешено движение со скоростью не более 110 км/ч, если знаки не устанавливают другое значение.' },
    { q: 'Ближе какого расстояния перед пешеходным переходом запрещена остановка?',
      a: ['3 м', '5 м', '10 м'], r: 1, p: '12.4',
      e: 'Остановка запрещена на пешеходных переходах и ближе 5 м перед ними.' },
    { q: 'Ближе какого расстояния от места остановки маршрутных транспортных средств запрещена остановка, если место обозначено разметкой 1.17 или указателем?',
      a: ['10 м', '15 м', '25 м'], r: 1, p: '12.4',
      e: 'Остановка запрещена ближе 15 м от мест остановки маршрутных транспортных средств или стоянки легковых такси, обозначенных разметкой 1.17, а при её отсутствии — от указателя места остановки.' },
    { q: 'На каком расстоянии от железнодорожного переезда запрещена стоянка?',
      a: ['Ближе 15 м', 'Ближе 30 м', 'Ближе 50 м'], r: 2, p: '12.5',
      e: 'Стоянка запрещена ближе 50 м с обеих сторон от железнодорожных переездов.' },
    { q: 'На каком расстоянии от автомобиля нужно выставить знак аварийной остановки вне населённого пункта?',
      a: ['Не менее 15 м', 'Не менее 30 м', 'Не менее 50 м'], r: 1, p: '7.2',
      e: 'Знак аварийной остановки выставляется на расстоянии, обеспечивающем своевременное предупреждение других водителей: не менее 15 м от транспортного средства в населённых пунктах и 30 м — вне населённых пунктов.' },
    { q: 'Кому должен уступить дорогу водитель при перестроении?',
      a: ['Транспортным средствам, движущимся попутно без изменения направления движения', 'Только транспортным средствам, которые находятся слева', 'Никому, если заранее включён указатель поворота'], r: 0, p: '8.4',
      e: 'При перестроении водитель должен уступить дорогу транспортным средствам, движущимся попутно без изменения направления движения. Указатель поворота не даёт преимущества.' },
    { q: 'Кому нужно уступить дорогу на перекрёстке равнозначных дорог?',
      a: ['Транспортным средствам, приближающимся слева', 'Транспортным средствам, приближающимся справа', 'Тому, кто едет быстрее'], r: 1, p: '13.11',
      e: 'На перекрёстке равнозначных дорог водитель безрельсового транспортного средства обязан уступить дорогу транспортным средствам, приближающимся справа (трамвай имеет преимущество независимо от направления).' },
    { q: 'С какого возраста ребёнка можно перевозить на переднем сиденье легкового автомобиля без детской удерживающей системы, пристегнув ремнём безопасности?',
      a: ['С 7 лет', 'С 10 лет', 'С 12 лет'], r: 2, p: '22.9',
      e: 'Детей в возрасте от 7 до 11 лет включительно на переднем сиденье легкового автомобиля перевозят только с использованием детских удерживающих систем. С 12 лет можно пристегнуть штатным ремнём безопасности.' }
  ];

  var $ = function (id) { return document.getElementById(id); };
  var i = 0, score = 0;

  function show(id) { ['q-intro', 'q-box', 'q-result'].forEach(function (x) { $(x).hidden = x !== id; }); }

  function render() {
    var item = Q[i];
    $('q-num').textContent = 'Вопрос ' + (i + 1) + ' из ' + Q.length;
    $('q-bar').style.width = (i / Q.length * 100) + '%';
    $('q-text').textContent = item.q;
    $('q-explain').hidden = true;
    $('q-next').hidden = true;
    var ul = $('q-opts');
    ul.innerHTML = '';
    item.a.forEach(function (text, k) {
      var li = document.createElement('li'), b = document.createElement('button');
      b.type = 'button';
      b.textContent = text;
      b.addEventListener('click', function () { answer(k); });
      li.appendChild(b);
      ul.appendChild(li);
    });
    $('q-text').focus();
  }

  function answer(k) {
    var item = Q[i], right = k === item.r;
    if (right) score++;
    var btns = $('q-opts').querySelectorAll('button');
    btns.forEach(function (b, n) {
      b.disabled = true;
      if (n === item.r) b.classList.add('right');
      else if (n === k) b.classList.add('wrong');
    });
    var ex = $('q-explain');
    ex.innerHTML = '<p><b>' + (right ? 'Верно.' : 'Неверно. Правильный ответ: ' + item.a[item.r] + '.') + '</b></p><p></p>' +
      '<p><a href="' + PDD + '" target="_blank" rel="noopener">Пункт ' + item.p + ' ПДД РФ</a></p>';
    ex.querySelectorAll('p')[1].textContent = item.e;
    ex.hidden = false;

    if (i === Q.length - 1) {
      // ответ на 10-й вопрос — тренажёр пройден
      window.track('pdd_test_complete', { score: score });
      $('q-next').textContent = 'Показать результат';
    } else {
      $('q-next').textContent = 'Следующий вопрос';
    }
    $('q-next').hidden = false;
  }

  $('q-next').addEventListener('click', function () {
    if (i < Q.length - 1) { i++; render(); return; }
    $('q-score').textContent = score;
    $('q-verdict').textContent = score >= 9 ? 'Отличный результат — с такими знаниями теория пойдёт легко.'
      : score >= 6 ? 'Неплохо, но несколько тем стоит повторить.'
      : 'Есть над чем поработать — разберём эти темы на теории.';
    show('q-result');
    $('q-result-h').focus();
  });

  function start() { i = 0; score = 0; show('q-box'); render(); }
  $('q-start').addEventListener('click', start); // pdd_test_start отправляет analytics.js по data-event
  $('q-again').addEventListener('click', start);
})();
